def set_para_text(par, text):
    if not par.runs:
        par.add_run(text)
        return
    par.runs[0].text = text
    for r in par.runs[1:]:
        r.text = ""


def remove_par(par):
    parent = par._p.getparent()
    if parent is not None:
        parent.remove(par._p)



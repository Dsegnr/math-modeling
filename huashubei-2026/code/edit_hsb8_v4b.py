    for p in paras:
        if p.text.strip().startswith(prefix):
            target = p
            break
    if target is None:
        warn.append(prefix[:40])
        continue
    set_para_text(target, new_text)
    n = 0
    for dpre in dels:
        for p in list(paras):
            if p is target:
                continue
            if p.text.strip().startswith(dpre):
                remove_par(p)
                n += 1
                break
    done.append(prefix[:30])


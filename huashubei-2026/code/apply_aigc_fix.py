def to_pattern(s):
    """把原句转正则：空白（含换行/制表）容错。"""
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c in " \t\n":
            out.append(r"\s+")
            while i < len(s) and s[i] in " \t\n":
                i += 1
        else:
            out.append(re.escape(c))
            i += 1
    return "".join(out)


